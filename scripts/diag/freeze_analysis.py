def main() -> None:
    previous = json.loads(OUTPUT.read_text()) if OUTPUT.exists() else None
    if previous is not None and previous["rules"] != RULES:
        raise SystemExit("the frozen rules differ from this script; refusing to overwrite them")
    code_root = HOME / "blt/code"
    checkpoints = {run: {"path": str(HOME / f"blt/runs/{run}/ckpt/bytes-3000000000.pt")} for run in RUNS}
    for run, row in checkpoints.items():
        known = (previous or {}).get("checkpoints", {}).get(run, {}).get("sha256")
        row["sha256"] = known or sha256(Path(row["path"]))
    manifest = {
        "frozen": previous["frozen"] if previous else datetime.now(timezone.utc).isoformat(),
        "updated": datetime.now(timezone.utc).isoformat(),
        "git_revision": subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True,
                                       cwd=code_root).stdout.strip(),
        "checkpoints": checkpoints,
        "tokenizers": {"gpt2-50k": sha256(HOME / "blt/models/gpt2-tokenizer/tokenizer.json"),
                       "fineweb-16k": sha256(HOME / "blt/data/tokenizer16k-v1/tokenizer.json")},
        "data": {"supply_manifest": sha256(HOME / "blt/data/supply-v1/manifest.json"),
                 "test_bin": sha256(HOME / "blt/data/supply-v1/test.bin"),
                 "piqa_dir": str(HOME / "blt/data/eval/piqa"), "hellaswag_dir": str(HOME / "blt/data/eval/hellaswag")},
        "code": {path: sha256(code_root / path) for path in CODE},
        "precision": "configure_matmul_precision(): bf16 autocast, reduced-precision bf16 reductions off",
        "rules": RULES,
    }
    OUTPUT.write_text(json.dumps(manifest, indent=1) + "\n")
    missing = [run for run, row in checkpoints.items() if row["sha256"] is None]
    print(f"wrote {OUTPUT}; checkpoints pending: {missing or 'none'}")


if __name__ == "__main__":
    main()
